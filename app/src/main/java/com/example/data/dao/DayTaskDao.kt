package com.example.data.dao

import androidx.room.Dao
import androidx.room.Delete
import androidx.room.Insert
import androidx.room.OnConflictStrategy
import androidx.room.Query
import androidx.room.Update
import com.example.data.model.DayTask
import com.example.data.model.TaskMode
import kotlinx.coroutines.flow.Flow

@Dao
interface DayTaskDao {
    @Query("SELECT * FROM day_tasks WHERE isDiscarded = 0 ORDER BY isCompleted ASC, date ASC, time ASC")
    fun getAllTasks(): Flow<List<DayTask>>

    @Query("SELECT * FROM day_tasks WHERE date = :date AND isDiscarded = 0 ORDER BY isCompleted ASC, time ASC")
    fun getTasksForDate(date: String): Flow<List<DayTask>>

    @Query("SELECT * FROM day_tasks WHERE isDiscarded = 0")
    suspend fun getAllUndiscardedTasksList(): List<DayTask>

    @Query("SELECT * FROM day_tasks WHERE date = :date AND isDiscarded = 0")
    suspend fun getTasksForDateList(date: String): List<DayTask>

    @Query("SELECT * FROM day_tasks WHERE date = :date AND mode = :mode AND isDiscarded = 0 ORDER BY isCompleted ASC, time ASC")
    fun getTasksForDateAndMode(date: String, mode: TaskMode): Flow<List<DayTask>>

    @Query("SELECT * FROM day_tasks WHERE mode = :mode AND isDiscarded = 0 ORDER BY isCompleted ASC, date ASC, time ASC")
    fun getTasksByMode(mode: TaskMode): Flow<List<DayTask>>

    @Query("SELECT * FROM day_tasks WHERE id = :id LIMIT 1")
    suspend fun getTaskById(id: Long): DayTask?

    @Insert(onConflict = OnConflictStrategy.REPLACE)
    suspend fun insertTask(task: DayTask): Long

    @Insert(onConflict = OnConflictStrategy.REPLACE)
    suspend fun insertTasks(tasks: List<DayTask>): List<Long>

    @Update
    suspend fun updateTask(task: DayTask)

    @Delete
    suspend fun deleteTask(task: DayTask)

    @Query("DELETE FROM day_tasks WHERE id = :id")
    suspend fun deleteTaskById(id: Long)

    @Query("UPDATE day_tasks SET isCompleted = :completed WHERE id = :id")
    suspend fun setTaskCompleted(id: Long, completed: Boolean)

    @Query("UPDATE day_tasks SET isCompleted = 1, isDiscarded = 1 WHERE id = :id")
    suspend fun markTaskPassedAndDiscarded(id: Long)

    @Query("UPDATE day_tasks SET isVoidedDueToExam = 1, voidReason = :reason WHERE id = :id")
    suspend fun voidTaskDueToExam(id: Long, reason: String)

    @Query("DELETE FROM day_tasks WHERE date = :date AND linkedClassId IS NOT NULL")
    suspend fun deleteAutoGeneratedTasksForDate(date: String)

    @Query("DELETE FROM day_tasks")
    suspend fun clearAllTasks()
}
